const dictionary: Record<Lang, Record<string, string>> = { ru, en };

export function normalizeLang(code: string | null | undefined): Lang {
  if (!code) return 'ru';
  const lower = code.toLowerCase();
  if (['ru', 'uk', 'be', 'kk', 'uz', 'ky', 'tg', 'hy', 'az', 'ka', 'mo'].some((prefix) => lower.startsWith(prefix))) {
    return 'ru';
  }
  return 'en';
}

export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const template = dictionary[lang][key] ?? dictionary.ru[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function kindLabel(lang: Lang, kind: string): string {
  const key = `kind.${kind}`;
  return dictionary[lang][key] ?? dictionary.ru[key] ?? kind;
}
